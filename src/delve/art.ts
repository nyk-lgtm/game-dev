// ASCII art for Delve: monster and item billboards, stairs, title and end screens.
//
// Conventions (relied on by the renderer):
// - printable ASCII only (codes 32-126);
// - every row of one piece has the same length;
// - ' ' is transparent;
// - a character cell is ~1.6x taller than wide, so the art is drawn wide;
// - `accents` keys are characters that appear only in the accent spots
//   (eyes, flames, liquids), so they can be recolored safely.

export interface Art {
  rows: string[];
  /** Optional per-character color overrides: char -> CSS color (e.g. eyes). */
  accents?: Record<string, string>;
}


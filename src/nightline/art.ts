// ASCII art for Nightline. Printable ASCII only; ' ' is transparent. Every row
// of a piece has the same width. Cells are ~1.6x taller than wide, so shapes are
// drawn wide. Sprites stand on their last row; `accents` color highlight chars.

export interface Art {
  rows: string[];
  /** char -> CSS color for highlights (lights, windows, flames). Only map chars used solely for those highlights. */
  accents?: Record<string, string>;
}

const TAIL = '#ff3355';
const LAMP = '#ffcf6b';
/** Right-pad rows to one width (for art written without trailing spaces). */
const pad = (w: number, rows: string[]): string[] => rows.map((r) => r.padEnd(w));


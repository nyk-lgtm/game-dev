// Brink daily puzzle pool: `npx vite-node scripts/brink/puzzles.ts 400 [seed0]`
// Plays AI self-play games (Normal vs Normal, every fourth game Normal vs Easy for
// variety) and keeps positions where the side to move forces a win in exactly 2
// or 3 moves with exactly one winning first move (verified by the exact search in
// core/puzzle.ts). One puzzle per game, the first qualifying position, stored
// with the solver as light. Writes src/brink/core/pool.ts.

import { writeFileSync } from 'node:fs';
import { chooseMove, type Level } from '../../src/brink/core/ai';
import { LIGHT, play, newGame, clone, type Side, type State } from '../../src/brink/core/rules';
import { encodeRecord, mirrored, recordOf, winningMoves } from '../../src/brink/core/puzzle';

const want = Number(process.argv[2] ?? 400);
const seed0 = Number(process.argv[3] ?? 50000);
const out: string[] = [];
const counts = { 2: 0, 3: 0 };
const t0 = performance.now();
let games = 0;

/** Exactly-n puzzle with a unique first move? */
function qualifies(s: State): number {
  for (let n = 1; n <= 3; n++) {
    const w = winningMoves(s, n, n === 3 ? 400000 : 200000);
    if (w === null) return 0;
    if (w.length === 0) continue;
    return n >= 2 && w.length === 1 ? n : 0;
  }
  return 0;
}

for (let seed = seed0; out.length < want; seed++) {
  games++;
  const first: Side = seed % 2 ? LIGHT : 2;
  const s = newGame(seed, first);
  const levels: Level[] = seed % 4 === 0 ? ['normal', 'easy'] : ['normal', 'normal'];
  let found: { s: State; n: number } | null = null;
  while (!s.winner && s.ply < 120) {
    // Only look once someone is close to winning (puzzles need a stone or two gone).
    if (s.lost[1] + s.lost[2] >= 2 || s.ply >= 18) {
      const n = qualifies(s);
      if (n) {
        found = { s: clone(s), n };
        break;
      }
    }
    play(s, chooseMove(s, levels[(s.turn + seed) % 2]).move);
  }
  if (!found) continue;
  const solverIsLight = found.s.turn === LIGHT;
  const st = solverIsLight ? found.s : mirrored(found.s);
  out.push(encodeRecord(recordOf(st, found.n, !solverIsLight, first)));
  counts[found.n as 2 | 3]++;
  if (out.length % 25 === 0) console.log(`${out.length} puzzles from ${games} games (${counts[2]} in 2, ${counts[3]} in 3), ${((performance.now() - t0) / 1000).toFixed(0)} s`);
}

const body = `// Generated by scripts/brink/puzzles.ts (${out.length} puzzles from ${games} self-play games, seeds from ${seed0}).
// Each is a "win in N" position with a single winning first move, stored with the
// solver as light: seed:ply:lost(L,D):mirror+first:N:cells. Do not edit by hand.

export const POOL: readonly string[] = [
${out.map((r) => `  '${r}',`).join('\n')}
];
`;
writeFileSync(new URL('../../src/brink/core/pool.ts', import.meta.url), body);
console.log(`wrote ${out.length} puzzles (${counts[2]} in 2, ${counts[3]} in 3) from ${games} games`);
